// PRIVATE_SPEC: offline analysis for LCD beat sync. Decodes each BGM in
// headless Chromium and stores a 30 Hz low-band / full-band loudness curve.
// The game never routes audio through WebAudio for this (file:// safe).
// Usage: node tools/build-bgm-pulse.cjs  (needs playwright; dev only)
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const { execSync } = require('node:child_process');
let playwright;
try { playwright = require('playwright'); } catch { playwright = require(path.join(execSync('npm root -g').toString().trim(), 'playwright')); }

const root = path.resolve(__dirname, '..');
const RATE = 30;
const tracks = ['red-seven.mp3', 'blue-seven.mp3', 'bigred-v.mp3', 'bigblue-v.mp3', 'regtrim.mp3', 'kaimai-boost-2aa.mp3', 'wwssflip.mp3', 'baba-cz.mp3', 'shibaku-cz.mp3', 'unko-cz.mp3'];

(async () => {
  const server = http.createServer((req, res) => {
    const file = path.join(root, 'assets', 'audio', path.basename(decodeURIComponent(req.url.split('?')[0])));
    if (!fs.existsSync(file)) { res.writeHead(404); res.end(); return; }
    res.writeHead(200, { 'Content-Type': 'audio/mpeg', 'Access-Control-Allow-Origin': '*' });
    fs.createReadStream(file).pipe(res);
  }).listen(0);
  const port = server.address().port;
  const browser = await playwright.chromium.launch();
  const page = await browser.newPage();
  await page.goto(`http://localhost:${port}/none`).catch(() => {});
  const out = {};
  for (const name of tracks) {
    const result = await page.evaluate(async ({ url, rate }) => {
      const data = await (await fetch(url)).arrayBuffer();
      const sampleRate = 11025;
      const decoded = await new OfflineAudioContext(1, 1, sampleRate).decodeAudioData(data);
      const render = async (lowpass) => {
        const ctx = new OfflineAudioContext(1, decoded.length, sampleRate);
        const src = ctx.createBufferSource(); src.buffer = decoded;
        let node = src;
        if (lowpass) { const f = ctx.createBiquadFilter(); f.type = 'lowpass'; f.frequency.value = 140; f.Q.value = 0.7; node.connect(f); node = f; }
        node.connect(ctx.destination); src.start();
        return (await ctx.startRendering()).getChannelData(0);
      };
      const curve = (samples) => {
        const hop = Math.round(sampleRate / rate), frames = Math.floor(samples.length / hop), values = new Float32Array(frames);
        for (let i = 0; i < frames; i++) { let sum = 0; for (let j = i * hop; j < (i + 1) * hop; j++) sum += samples[j] * samples[j]; values[i] = Math.sqrt(sum / hop); }
        const sorted = [...values].sort((a, b) => a - b), peak = sorted[Math.floor(sorted.length * 0.985)] || 1;
        let text = ''; for (const v of values) text += String.fromCharCode(Math.min(255, Math.round(v / peak * 230)));
        return btoa(text);
      };
      return { duration: decoded.duration, low: curve(await render(true)), level: curve(await render(false)) };
    }, { url: `http://localhost:${port}/${name}`, rate: RATE });
    out[name] = { rate: RATE, ...result };
    console.log(name, result.duration.toFixed(1) + 's');
  }
  await browser.close(); server.close();
  fs.writeFileSync(path.join(root, 'assets', 'audio', 'bgm-pulse.js'),
    `// Generated by tools/build-bgm-pulse.cjs. Loudness curves only (no audio data).\nwindow.ShibakuBgmPulse = ${JSON.stringify(out)};\n`);
  console.log('Wrote assets/audio/bgm-pulse.js');
})();
